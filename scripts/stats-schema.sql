CREATE TABLE IF NOT EXISTS events (id INTEGER PRIMARY KEY AUTOINCREMENT, ts INTEGER NOT NULL, day TEXT NOT NULL, hour INTEGER NOT NULL, vid TEXT NOT NULL, name TEXT NOT NULL, page TEXT, place TEXT, extra TEXT, device TEXT, ref TEXT, standalone INTEGER DEFAULT 0, num INTEGER);
CREATE INDEX IF NOT EXISTS events_day ON events (day);
CREATE INDEX IF NOT EXISTS events_name_day ON events (name, day);
CREATE INDEX IF NOT EXISTS events_ts ON events (ts);
CREATE TABLE IF NOT EXISTS salts (day TEXT PRIMARY KEY, salt TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS sessions (token TEXT PRIMARY KEY, expires INTEGER NOT NULL);
CREATE TABLE IF NOT EXISTS login_fails (id INTEGER PRIMARY KEY AUTOINCREMENT, ipkey TEXT NOT NULL, ts INTEGER NOT NULL);
CREATE INDEX IF NOT EXISTS login_fails_ts ON login_fails (ts);
